/** JST の YYYY-MM-DD */
export function jstDateKeyFromDate(now = new Date()): string {
  return now.toLocaleDateString("en-CA", { timeZone: "Asia/Tokyo" });
}

/** 東証現物が休場か（土日は別判定。ここは祝日・年末年始） */
export function isJpEquityExchangeHoliday(now = new Date()): boolean {
  return TSE_CASH_HOLIDAYS.has(jstDateKeyFromDate(now));
}

export function listKnownJpEquityHolidays(): string[] {
  return [...TSE_CASH_HOLIDAYS].sort();
}
